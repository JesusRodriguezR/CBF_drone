from geometry_msgs.msg import PointStamped, Twist
from nav_msgs.msg import Odometry
import math
from std_msgs.msg import Float64

import rclpy
from rclpy.node import Node


class ControlServices(Node):

    def __init__(self):
        super().__init__('control_services')
        self.declare_parameter('hover_height', 0.5)
        self.declare_parameter('landing_height', 0.05)
        self.declare_parameter('robot_prefix', '/crazyflie')
        self.declare_parameter('incoming_twist_topic', '/cmd_vel')
        self.declare_parameter('max_ang_z_rate', 0.4)
        self.declare_parameter('max_vertical_speed', 0.5)
        self.declare_parameter('altitude_kp', 1.2)
        self.declare_parameter('altitude_ki', 0.15)
        self.declare_parameter('altitude_kd', 0.25)
        self.declare_parameter('lateral_position_kp', 0.8)
        self.declare_parameter('max_lateral_correction', 0.25)
        self.declare_parameter('command_timeout', 0.5)
        self.declare_parameter('desired_yaw', 0.0)
        self.declare_parameter('yaw_kp', 3.0)
        self.declare_parameter('max_yaw_correction', 0.5)

        hover_height = self.get_parameter('hover_height').value
        landing_height = self.get_parameter('landing_height').value
        robot_prefix = self.get_parameter('robot_prefix').value
        incoming_twist_topic = self.get_parameter('incoming_twist_topic').value
        max_ang_z_rate = self.get_parameter('max_ang_z_rate').value
        max_vertical_speed = self.get_parameter('max_vertical_speed').value
        self.lateral_position_kp = self.get_parameter('lateral_position_kp').value
        self.max_lateral_correction = self.get_parameter('max_lateral_correction').value
        self.command_timeout = self.get_parameter('command_timeout').value
        self.desired_yaw = self.get_parameter('desired_yaw').value
        self.yaw_kp = self.get_parameter('yaw_kp').value
        self.max_yaw_correction = self.get_parameter('max_yaw_correction').value

        self.publisher_ = self.create_publisher(Twist, robot_prefix + incoming_twist_topic, 10)
        self.odom_subscriber = self.create_subscription(
            Odometry, robot_prefix + '/odom', self.odometry_callback, 10)
        self.cmd_subscriber = self.create_subscription(
            Twist, incoming_twist_topic, self.cmd_vel_callback, 10)
        self.target_subscriber = self.create_subscription(
            PointStamped, '/greenhouse/fsm_target', self.target_callback, 10)
        self.yaw_target_subscriber = self.create_subscription(
            Float64, '/greenhouse/fsm_desired_yaw', self.yaw_target_callback, 10)
        self.timer = self.create_timer(0.02, self.timer_callback)

        self.current_pose = Odometry().pose.pose
        self.current_vertical_velocity = 0.0
        self.takeoff_height = hover_height
        self.landing_height = landing_height
        self.max_vertical_speed = max_vertical_speed
        self.max_ang_z_rate = max_ang_z_rate
        self.is_flying = False
        self.flight_mode = 'LANDED'
        self.target_height = 0.0
        self.altitude_integral = 0.0
        self.previous_altitude_error = 0.0
        self.last_control_time = None
        self.teleop_cmd = Twist()
        self.target_y = None
        self.last_command_time = self.get_clock().now()

    def timer_callback(self):
        msg = self.teleop_cmd
        new_cmd_msg = Twist()

        command_age = (self.get_clock().now() - self.last_command_time).nanoseconds * 1e-9
        if command_age > self.command_timeout:
            # Fail safe if the planner disappears: stop horizontal motion and
            # request a controlled landing if already airborne.
            if self.is_flying:
                msg = Twist()
                msg.linear.z = -0.2
            else:
                msg = Twist()

        # Positive/negative vertical teleop commands request takeoff/landing.
        # The actual vertical command is generated by a bounded PID loop.
        if msg.linear.z > 0.05 and not self.is_flying:
            self.flight_mode = 'TAKEOFF'
            self.target_height = self.takeoff_height
        elif msg.linear.z < -0.05 and self.is_flying:
            self.flight_mode = 'LAND'
            self.target_height = self.landing_height

        if self.flight_mode in ('TAKEOFF', 'HOVER', 'LAND'):
            now = self.get_clock().now().nanoseconds * 1e-9
            if self.last_control_time is None:
                dt = 0.02
            else:
                dt = max(1e-3, min(now - self.last_control_time, 0.1))
            self.last_control_time = now

            altitude = self.current_pose.position.z
            error = self.target_height - altitude
            self.altitude_integral = max(-0.5, min(0.5,
                self.altitude_integral + error * dt))
            derivative = -self.current_vertical_velocity
            altitude_kp = self.get_parameter('altitude_kp').value
            altitude_ki = self.get_parameter('altitude_ki').value
            altitude_kd = self.get_parameter('altitude_kd').value
            vertical_speed = (
                altitude_kp * error
                + altitude_ki * self.altitude_integral
                + altitude_kd * derivative)
            new_cmd_msg.linear.z = max(
                -self.max_vertical_speed,
                min(self.max_vertical_speed, vertical_speed))

            if self.flight_mode == 'TAKEOFF' and abs(error) < 0.03 and abs(self.current_vertical_velocity) < 0.1:
                self.flight_mode = 'HOVER'
                self.is_flying = True
                self.altitude_integral = 0.0
                self.get_logger().info('Takeoff completed')
            elif self.flight_mode == 'LAND' and altitude < 0.08 and abs(self.current_vertical_velocity) < 0.1:
                self.flight_mode = 'LANDED'
                self.is_flying = False
                new_cmd_msg = Twist()
                self.altitude_integral = 0.0
                self.get_logger().info('Landing completed')

        # Horizontal and yaw commands are passed through only while airborne.
        if self.is_flying:
            # Close the outer lateral position loop around the FSM lane target.
            # The Gazebo multicopter plugin remains the inner velocity /
            # attitude / angular-rate controller.
            lateral_error = 0.0 if self.target_y is None else self.target_y - self.current_pose.position.y
            correction = self.lateral_position_kp * lateral_error
            correction = max(-self.max_lateral_correction,
                             min(self.max_lateral_correction, correction))
            world_vx = msg.linear.x
            world_vy = max(-self.max_lateral_correction,
                           min(self.max_lateral_correction,
                               msg.linear.y + correction))

            # Gazebo's MulticopterVelocityControl and the Crazyflie velocity
            # interface consume horizontal Twist commands in body frame.
            # FSM planning and odometry are world-frame, so rotate here using
            # the measured yaw before sending the command to the vehicle.
            q = self.current_pose.orientation
            yaw = math.atan2(
                2.0 * (q.w * q.z + q.x * q.y),
                1.0 - 2.0 * (q.y * q.y + q.z * q.z))
            new_cmd_msg.linear.x = math.cos(yaw) * world_vx + math.sin(yaw) * world_vy
            new_cmd_msg.linear.y = -math.sin(yaw) * world_vx + math.cos(yaw) * world_vy

            # Hold the camera's forward heading.  The Crazyflie/Gazebo
            # interface accepts body-frame yaw rate, so close a small outer
            # yaw loop around the odometry heading.
            yaw_error = (self.desired_yaw - yaw + math.pi) % (2.0 * math.pi) - math.pi
            new_cmd_msg.angular.z = max(
                -self.max_yaw_correction,
                min(self.max_yaw_correction, self.yaw_kp * yaw_error))
            new_cmd_msg.angular.x = msg.angular.x
            new_cmd_msg.angular.y = msg.angular.y

        # Cap the angular rate command in the z axis
        if abs(msg.angular.z) > self.max_ang_z_rate:
            new_cmd_msg.angular.z = self.max_ang_z_rate * abs(msg.angular.z)/msg.angular.z

        self.publisher_.publish(new_cmd_msg)

    def odometry_callback(self, msg):
        self.current_pose = msg.pose.pose
        self.current_vertical_velocity = msg.twist.twist.linear.z

    def takeoff_callback(self, request, response):

        response.success = True
        return response

    def cmd_vel_callback(self, msg):
        self.teleop_cmd = msg
        self.last_command_time = self.get_clock().now()

    def target_callback(self, msg):
        self.target_y = msg.point.y

    def yaw_target_callback(self, msg):
        self.desired_yaw = msg.data


def main(args=None):
    rclpy.init(args=args)

    control_services = ControlServices()

    rclpy.spin(control_services)

    rclpy.shutdown()


if __name__ == '__main__':
    main()
